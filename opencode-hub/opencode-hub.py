def in_nets(scope, nets) -> bool:
    try:
        ip = ipaddress.ip_address((scope.get("client") or ("", 0))[0])
    except ValueError:
        return False
    return any(ip in net for net in nets)


def log(msg: str) -> None:
    print(f"opencode-hub: {msg}", file=sys.stderr, flush=True)


def load_token(path: str) -> bytes | None:
    """The bearer token from `path`, or None when the file is unusable. The reason is logged, never the
    content; None fails closed (every protected request gets 401) instead of crash-looping the unit that
    every MCP client depends on."""
    try:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
    except OSError as exc:
        log(f"token file {path} unusable ({exc.__class__.__name__}): refusing every protected request")
        return None
    with os.fdopen(fd, "rb") as fh:
        st = os.fstat(fh.fileno())
        if not stat.S_ISREG(st.st_mode) or st.st_mode & 0o077:
            log(f"token file {path} must be a regular file with mode 0600: refusing every protected request")
            return None
        value = fh.read(4096).strip()
    # printable ASCII only (what an HTTP header can carry); hub_token.read_token applies the same rule
    if len(value) < TOKEN_MIN_BYTES or not all(0x21 <= c <= 0x7E for c in value):
        log(f"token file {path} must hold one printable token of >= {TOKEN_MIN_BYTES} bytes:"
            " refusing every protected request")
        return None
    return value


# the loaded token (bytes) or None; only consulted when TOKEN_FILE is set
EXPECTED_BEARER = load_token(TOKEN_FILE) if TOKEN_FILE else None


def quiet_errlog(prefix: bytes):
    """A writable stderr target for one chatty child: a daemon thread drains the pipe and forwards
    every line that does not start with `prefix` to the hub's stderr. Popen needs a real fd, so a
    plain filtering file-like will not do. The write end stays open across child restarts, so the
    pump never sees a premature EOF; the thread dies with the hub. A failed forward drops that line
    only (the pump must keep draining, or the child blocks on a full pipe), and every 1000 dropped
    prefix lines leave one digest line, so silence stays distinguishable from a dead filter."""
    read_fd, write_fd = os.pipe()

    def pump():
        dropped = 0
        with os.fdopen(read_fd, "rb", buffering=0) as src:
            for line in iter(src.readline, b""):
                if line.startswith(prefix):
                    dropped += 1
                    if dropped % 1000:
                        continue
                    line = b"opencode-hub: dropped %d %s stderr lines so far\n" % (dropped, prefix)
                try:
                    sys.stderr.buffer.write(line)
                    sys.stderr.buffer.flush()
                except (OSError, ValueError):
                    pass

    threading.Thread(target=pump, name="stderr-filter", daemon=True).start()
    return os.fdopen(write_fd, "wb", buffering=0)


async def deny(scope, receive, send, status=403):
    await Response("forbidden\n" if status == 403 else "not found\n", status_code=status)(scope, receive, send)


async def unauthorized(scope, receive, send):
    await Response("unauthorized\n", status_code=401,
                   headers={"www-authenticate": 'Bearer realm="opencode-hub"'})(scope, receive, send)


def token_verdict(scope) -> str | None:
    """None when the request may pass, else why not ("missing" / "wrong" / "unusable token file").
    Reads the module settings at call time, so tests can switch them."""
    if not TOKEN_FILE:
        return None
    if scope["method"] in ("GET", "HEAD") and TOKEN_EXEMPT_RE.match(scope["path"]):
        return None
    if not TOKEN_OFFBOX and not in_nets(scope, LOCAL):
        return None
    if EXPECTED_BEARER is None:
        return "unusable token file"
    # raw bytes, never decoded: compare_digest runs in time independent of where the values differ
    value = next((v for k, v in scope["headers"] if k.lower() == b"authorization"), None)
    if value is None:
        return "missing"
    scheme, _, credential = value.strip().partition(b" ")
    if scheme.lower() == b"bearer" and hmac.compare_digest(credential.strip(), EXPECTED_BEARER):
        return None
    return "wrong"


class Guard:
    """Pure ASGI (keeps MCP SSE streams unbuffered): source network, Host, no-browser and token checks."""

    def __init__(self, app):
        self.app = app
        self.denied_logged = {}  # peer -> monotonic time of its last 401 log line (one per minute)

    async def __call__(self, scope, receive, send):
        if scope["type"] == "websocket":  # no websocket routes: refuse before any app code runs
            await send({"type": "websocket.close", "code": 1008})
            return
        if scope["type"] == "http":
            headers = {k.decode().lower(): v.decode() for k, v in scope["headers"]}
            host = headers.get("host", "").rsplit(":", 1)[0].strip("[]")
            if not in_nets(scope, ALLOWED_NETS) or host not in ALLOWED_HOSTS or "origin" in headers:
                await deny(scope, receive, send)
                return
            reason = token_verdict(scope)
            if reason is not None:
                self.log_denied(scope, reason)
                if TOKEN_ENFORCE:
                    await unauthorized(scope, receive, send)
                    return
        await self.app(scope, receive, send)

    def log_denied(self, scope, reason: str) -> None:
        peer, now = (scope.get("client") or ("?", 0))[0], time.monotonic()
        if now - self.denied_logged.get(peer, -120.0) < 60:
            return
        if len(self.denied_logged) > 1024:
            self.denied_logged.clear()
        self.denied_logged[peer] = now
        verdict = "401" if TOKEN_ENFORCE else "report-only (let through, would be 401)"
        log(f"{verdict} {scope['method']} {scope['path'][:120]!r} from {peer}: {reason} bearer token"
            " (further ones from this peer are not logged for 60 s)")


def stdio_params(server: dict) -> StdioServerParameters:
    return StdioServerParameters(
        command=server["command"], args=list(server.get("args", [])),
        env={k: str(v) for k, v in (server.get("env") or {}).items()},
        cwd=server.get("cwd") or os.environ.get("HOME", "/root"))


def message(root) -> SessionMessage:
    return SessionMessage(types.JSONRPCMessage(root))


def error_reply(req_id, code: int, text: str) -> SessionMessage:
    return message(types.JSONRPCError(jsonrpc="2.0", id=req_id, error=types.ErrorData(code=code, message=text)))


async def deliver(stream, msg: SessionMessage) -> None:
    with contextlib.suppress(anyio.ClosedResourceError, anyio.BrokenResourceError):
        await stream.send(msg)


class PerSessionBridge:
    """Duck-typed MCP 'server' for StreamableHTTPSessionManager: relays one HTTP session's JSON-RPC
    messages verbatim to a dedicated stdio child and back (for servers with per-session state)."""

    def __init__(self, server: dict):
        self.params = stdio_params(server)

    def create_initialization_options(self):
        return None

    async def run(self, http_read, http_write, _init_options, stateless=False):
        async with stdio_client(self.params, errlog=sys.stderr) as (child_read, child_write):
            async with anyio.create_task_group() as tg:
                async def pump(src, dst):
                    async for msg in src:
                        if not isinstance(msg, Exception):
                            await dst.send(msg)
                    tg.cancel_scope.cancel()  # either side closed: end the session and the child

                tg.start_soon(pump, http_read, child_write)
                tg.start_soon(pump, child_read, http_write)


class SharedBridge:
    """One stdio child shared by every HTTP session. The hub performs the MCP handshake once and
    answers each session's initialize from it; request ids and progress tokens are rewritten to
    hub-unique ids on the way in and restored on the way out; server notifications without an owner
    (list_changed, logging) go to every session. The child is started on first use and restarted if
    it exits; requests in flight at that moment get an error."""

    def __init__(self, name: str, server: dict):
        self.name, self.params = name, stdio_params(server)
        self.errlog = quiet_errlog(STDERR_DROP_PREFIXES[name]) if name in STDERR_DROP_PREFIXES else sys.stderr
        self.ids = itertools.count(1)
        self.pending = {}    # hub id -> (session stream, client id)
        self.progress = {}   # hub token -> (session stream, client token, client request id)
        self.sessions = set()
        self.init_result = None
        self.handshake_done = None
        self.ready = anyio.Event()
        self.child_write = None
        self.started = False
        self.tg = None

    def create_initialization_options(self):
        return None

    async def supervise(self):
        while True:
            try:
                async with stdio_client(self.params, errlog=self.errlog) as (child_read, child_write):
                    async with anyio.create_task_group() as tg:
                        self.child_write = child_write
                        tg.start_soon(self.dispatch, child_read, tg.cancel_scope)
                        await self.handshake(child_write)
                        self.ready.set()
                        await anyio.sleep_forever()
            except Exception as exc:  # child failed to start or crashed: retry, never take the hub down
                log(f"{self.name}: {type(exc).__name__}: {exc}")
            self.child_write, self.ready = None, anyio.Event()
            for stream, client_id in self.pending.values():
                await deliver(stream, error_reply(client_id, types.INTERNAL_ERROR, f"{self.name} MCP server restarted"))
            self.pending.clear()
            self.progress.clear()
            await anyio.sleep(RESTART_DELAY_S)

    async def handshake(self, child_write):
        self.handshake_done = anyio.Event()
        await child_write.send(message(types.JSONRPCRequest(
            jsonrpc="2.0", id=0, method="initialize",
            params={"protocolVersion": types.LATEST_PROTOCOL_VERSION, "capabilities": {},
                    "clientInfo": {"name": "opencode-hub", "version": "1"}})))
        with anyio.fail_after(60):
            await self.handshake_done.wait()
        await child_write.send(message(types.JSONRPCNotification(jsonrpc="2.0", method="notifications/initialized")))

    async def wait_ready(self) -> bool:
        # supervise() replaces the Event on every restart, so re-read it rather than wait on a stale one
        with anyio.move_on_after(90):
            while not self.ready.is_set():
                with anyio.move_on_after(1):
                    await self.ready.wait()
            return True
        return False

    async def dispatch(self, child_read, scope):
        async for item in child_read:
            if isinstance(item, Exception):
                continue
            msg = item.message.root
            if isinstance(msg, (types.JSONRPCResponse, types.JSONRPCError)):
                if msg.id == 0:  # the hub's own handshake
                    if isinstance(msg, types.JSONRPCError):
                        raise RuntimeError(f"initialize failed: {msg.error.message}")
                    self.init_result = msg.result
                    self.handshake_done.set()
                    continue
                stream, client_id = self.pending.pop(msg.id, (None, None))
                if stream is not None:
                    await deliver(stream, message(msg.model_copy(update={"id": client_id})))
            elif isinstance(msg, types.JSONRPCNotification):
                token = (msg.params or {}).get("progressToken")
                if msg.method == "notifications/progress" and token in self.progress:
                    stream, client_token, client_id = self.progress[token]
                    params = {**msg.params, "progressToken": client_token}
                    await deliver(stream, SessionMessage(
                        types.JSONRPCMessage(msg.model_copy(update={"params": params})),
                        metadata=ServerMessageMetadata(related_request_id=client_id)))
                elif msg.method in BROADCAST:
                    for stream in list(self.sessions):
                        await deliver(stream, message(msg))
            elif isinstance(msg, types.JSONRPCRequest):  # server -> client requests: no single owner
                reply = types.JSONRPCResponse(jsonrpc="2.0", id=msg.id, result={}) if msg.method == "ping" else \
                    types.JSONRPCError(jsonrpc="2.0", id=msg.id, error=types.ErrorData(
                        code=types.METHOD_NOT_FOUND, message=f"{msg.method} is not available through the shared hub"))
                await self.child_write.send(message(reply))
        self.child_write = None  # stdout closed: the child is gone; new requests get "restarting"
        scope.cancel()

    async def run(self, http_read, http_write, _init_options, stateless=False):
        if not self.started:
            self.started = True
            self.tg.start_soon(self.supervise)
        own = {}  # this session's client id -> hub id (for cancellation and cleanup)
        self.sessions.add(http_write)
        try:
            async for item in http_read:
                if isinstance(item, Exception):
                    continue
                msg = item.message.root
                if isinstance(msg, types.JSONRPCRequest):
                    if msg.method == "ping":
                        await deliver(http_write, message(types.JSONRPCResponse(jsonrpc="2.0", id=msg.id, result={})))
                        continue
                    if not await self.wait_ready():
                        await deliver(http_write, error_reply(msg.id, types.INTERNAL_ERROR, f"{self.name} is not starting"))
                        continue
                    if msg.method == "initialize":
                        await deliver(http_write, message(types.JSONRPCResponse(
                            jsonrpc="2.0", id=msg.id, result=self.init_result)))
                        continue
                    child_write = self.child_write
                    if child_write is None:
                        await deliver(http_write, error_reply(msg.id, types.INTERNAL_ERROR, f"{self.name} is restarting"))
                        continue
                    for client_id in [c for c, h in own.items() if h not in self.pending]:
                        del own[client_id]  # answered or failed: keep the map to in-flight calls
                    hub_id = next(self.ids)
                    params = copy.deepcopy(msg.params) if msg.params else msg.params
                    token = ((params or {}).get("_meta") or {}).get("progressToken")
                    if token is not None:
                        self.progress[f"p{hub_id}"] = (http_write, token, msg.id)
                        params["_meta"]["progressToken"] = f"p{hub_id}"
                    self.pending[hub_id] = (http_write, msg.id)
                    own[msg.id] = hub_id
                    try:
                        await child_write.send(message(msg.model_copy(update={"id": hub_id, "params": params})))
                    except (anyio.ClosedResourceError, anyio.BrokenResourceError):
                        if self.pending.pop(hub_id, None) is not None:
                            await deliver(http_write, error_reply(msg.id, types.INTERNAL_ERROR, f"{self.name} is restarting"))
                elif isinstance(msg, types.JSONRPCNotification) and msg.method == "notifications/cancelled":
                    hub_id = own.get((msg.params or {}).get("requestId"))
                    # a cancelled request gets no reply (MCP spec), so forget it even if a hung child never answers
                    if self.pending.pop(hub_id, None) is not None and self.child_write is not None:
                        with contextlib.suppress(anyio.ClosedResourceError, anyio.BrokenResourceError):
                            await self.child_write.send(message(msg.model_copy(
                                update={"params": {**msg.params, "requestId": hub_id}})))
                # other client notifications (initialized, roots/list_changed) and client responses
                # concern the hub's own handshake or per-client state the shared child must not see
        finally:
            self.sessions.discard(http_write)
            for hub_id in own.values():
                if self.pending.pop(hub_id, None) is not None and self.child_write is not None:
                    with contextlib.suppress(Exception):
                        await self.child_write.send(message(types.JSONRPCNotification(
                            jsonrpc="2.0", method="notifications/cancelled",
                            params={"requestId": hub_id, "reason": "client session closed"})))
            for token in [t for t, v in self.progress.items() if v[0] is http_write]:
                self.progress.pop(token, None)


def replay(body: bytes, receive):
    """An ASGI receive that hands back an already-read body, then defers to the real one."""
    pending = [{"type": "http.request", "body": body, "more_body": False}]

    async def again():
        return pending.pop() if pending else await receive()
    return again


class McpEndpoint:
    """Streamable HTTP endpoint backed by the SDK's session manager (shared + per-session modes)."""

    def __init__(self, name: str, manager: StreamableHTTPSessionManager, lan: bool, remote_only: bool = False):
        self.name, self.manager, self.lan, self.remote_only = name, manager, lan, remote_only
        self.remote = {}  # off-box session id -> time of its last request (monotonic)
        self.max_remote = MAX_REMOTE_PROCESS_SESSIONS if name in PER_SESSION else MAX_REMOTE_SESSIONS

    async def __call__(self, scope, receive, send):
        local = in_nets(scope, LOCAL)
        if (not self.lan and not local) or (self.remote_only and local):
            await deny(scope, receive, send, 404)
            return
        # _server_instances is the SDK's session map (mcp 1.27). It drops idle-reaped and crashed sessions
        # but keeps client-closed (DELETE) ones forever, so prune those before counting live sessions.
        sessions = self.manager._server_instances
        for sid in [sid for sid, t in sessions.items() if t.is_terminated]:
            sessions.pop(sid, None)
        self.remote = {sid: seen for sid, seen in self.remote.items() if sid in sessions}
        if scope["method"] == "POST":  # the SDK reads the whole body into memory: cap it first
            chunks, size, more = [], 0, True
            while more:
                event = await receive()
                if event["type"] == "http.disconnect":
                    return
                chunk = event.get("body", b"")
                size += len(chunk)
                if size > MCP_MAX_BODY:
                    await JSONResponse({"error": "body too large"}, status_code=413)(scope, receive, send)
                    return
                chunks.append(chunk)
                more = event.get("more_body", False)
            receive = replay(b"".join(chunks), receive)
        sid = next((v.decode() for k, v in scope["headers"] if k == b"mcp-session-id"), None)
        if local or sid is not None:
            if sid in self.remote:
                self.remote[sid] = time.monotonic()
            await self.manager.handle_request(scope, receive, send)
            return
        if len(self.remote) >= self.max_remote and not await self.evict_abandoned(sessions):
            await JSONResponse({"error": "too many sessions"}, status_code=503)(scope, receive, send)
            return

        async def send_and_track(event):
            if event["type"] == "http.response.start":
                sid = next((v.decode() for k, v in event.get("headers", []) if k.lower() == b"mcp-session-id"), None)
                if sid:
                    self.remote[sid] = time.monotonic()
            await send(event)

        await self.manager.handle_request(scope, receive, send_and_track)

    async def evict_abandoned(self, sessions) -> bool:
        """At the off-box cap, close the longest-quiet session nobody is attached to, instead of refusing.
        `opencode run` exits without DELETE, so a busy laptop fills every slot with sessions of processes
        that are already gone, and the 5-minute idle reap is too slow for one run every ~20 s (2026-10-05,
        Part F2: 5/10 runs saw 503). A session with a call in flight or an open GET stream (a live client
        listening) is never closed: when all of them are live, the cap holds and the caller gets 503."""
        for sid, _ in sorted(self.remote.items(), key=lambda item: item[1]):
            transport = sessions.get(sid)
            if transport is None or transport.is_terminated:
                self.remote.pop(sid, None)
                return True
            # in-flight calls and the GET stream (SDK 1.27 internals); if a later SDK renames it, treat every
            # session as live: the cap then answers 503 rather than closing a client that is still there
            if getattr(transport, "_request_streams", True):
                continue
            self.remote.pop(sid, None)
            await transport.terminate()
            return True
        return False


class NativeEndpoint:
    """Reverse proxy to a playwright-mcp process running its own multi-client HTTP server on loopback.
    The hub tracks its sessions to cap them and to DELETE ones abandoned by a sleeping laptop."""

    # with a token configured (F3), authorization (the hub's bearer token) stays at the hub, never
    # forwarded to the child; unset keeps the pre-F3 forwarding
    HOP = {b"host", b"connection", b"content-length", b"transfer-encoding", b"keep-alive", b"origin"} | (
        {b"authorization"} if TOKEN_FILE else set())

    def __init__(self, name: str, server: dict, lan: bool):
        self.name, self.lan, self.port = name, lan, NATIVE_PORTS[name]
        self.base = f"http://127.0.0.1:{self.port}/mcp"
        self.sessions = {}  # session id -> [last seen, open responses, opened from off-box]
        self.client = httpx.AsyncClient(timeout=httpx.Timeout(None, connect=5))
        command, args = server["command"], [*server.get("args", []), "--isolated",
                                            "--host", "127.0.0.1", "--port", str(self.port)]
        env = {k: str(v) for k, v in (server.get("env") or {}).items()}
        self.cwd = os.environ.get("HOME", "/root")
        self.argv = [command, *args]
        self.env = {**{k: v for k, v in os.environ.items() if k in ("PATH", "HOME", "USER", "LOGNAME", "LANG")}, **env}

    async def supervise(self):
        while True:
            try:
                async with await anyio.open_process(self.argv, env=self.env, cwd=self.cwd,
                                                    stdin=None, stdout=None, stderr=None) as proc:
                    await proc.wait()
                    log(f"{self.name}: exited with {proc.returncode}")
            except Exception as exc:
                log(f"{self.name}: {type(exc).__name__}: {exc}")
            self.sessions.clear()
            await anyio.sleep(RESTART_DELAY_S)

    async def reap(self):
        while True:
            await anyio.sleep(60)
            now = time.monotonic()
            for sid, (seen, streams, _remote) in list(self.sessions.items()):
                if streams == 0 and now - seen > SESSION_IDLE_S:
                    self.sessions.pop(sid, None)
                    with contextlib.suppress(httpx.HTTPError):
                        await self.client.delete(self.base, headers={"mcp-session-id": sid})

    async def __call__(self, scope, receive, send):
        local = in_nets(scope, LOCAL)
        if not self.lan and not local:
            await deny(scope, receive, send, 404)
            return
        # playwright's HTTP server only answers Host: localhost:<port>
        headers = [(b"host", f"localhost:{self.port}".encode())] + [
            (k, v) for k, v in scope["headers"] if k.lower() not in self.HOP]
        sid = next((v.decode() for k, v in scope["headers"] if k.lower() == b"mcp-session-id"), None)
        if sid is None and not local and sum(e[2] for e in self.sessions.values()) >= MAX_REMOTE_SESSIONS:
            await JSONResponse({"error": "too many sessions"}, status_code=503)(scope, receive, send)
            return
        body = b""
        while True:
            event = await receive()
            body += event.get("body", b"")
            if len(body) > MCP_MAX_BODY:
                await JSONResponse({"error": "body too large"}, status_code=413)(scope, receive, send)
                return
            if not event.get("more_body"):
                break
        query = ("?" + scope["query_string"].decode()) if scope.get("query_string") else ""
        try:
            request = self.client.build_request(scope["method"], self.base + query, headers=headers, content=body)
            upstream = await self.client.send(request, stream=True)
        except httpx.HTTPError:
            await JSONResponse({"error": f"{self.name} is starting"}, status_code=502)(scope, receive, send)
            return
        new_sid = upstream.headers.get("mcp-session-id")
        if sid is None and new_sid and upstream.status_code < 300:
            self.sessions[new_sid] = [time.monotonic(), 0, not local]
            sid = new_sid
        if scope["method"] == "DELETE" and sid:
            self.sessions.pop(sid, None)
        entry = self.sessions.get(sid)
        if entry is not None:
            entry[1] += 1
        try:
            await send({"type": "http.response.start", "status": upstream.status_code, "headers": [
                (k, v) for k, v in upstream.headers.raw if k.lower() not in self.HOP]})
            async with anyio.create_task_group() as tg:
                async def watch_disconnect():
                    while (await receive())["type"] != "http.disconnect":
                        pass
                    tg.cancel_scope.cancel()

                tg.start_soon(watch_disconnect)
                async for chunk in upstream.aiter_raw():
                    await send({"type": "http.response.body", "body": chunk, "more_body": True})
                await send({"type": "http.response.body", "body": b"", "more_body": False})
                tg.cancel_scope.cancel()
        except (OSError, httpx.HTTPError, anyio.ClosedResourceError, anyio.BrokenResourceError):
            pass
        finally:
            await upstream.aclose()
            if entry is not None:
                entry[0], entry[1] = time.monotonic(), entry[1] - 1


def build_app() -> Starlette:
    with open(SERVERS) as fh:
        servers = {n: s for n, s in json.load(fh)["mcpServers"].items() if s.get("command")}
    for name, entry in WORK_COPIES.items():
        base, env = entry[0], entry[1]
        launch = entry[2] if len(entry) > 2 else None
        if base in servers:
            servers[name] = copy.deepcopy(servers[base])
            servers[name]["env"] = {**(servers[name].get("env") or {}), **env}
            if launch:  # the work cbm: setpriv argv + a cwd the dropped-privilege child can enter
                servers[name].update(launch)
    lan = OFFBOX
    no_sdk_host_check = TransportSecuritySettings(enable_dns_rebinding_protection=False)  # Guard does it
    shared, managers, native = [], {}, {}
    for name, server in servers.items():
        if name in NATIVE_PORTS:
            native[name] = NativeEndpoint(name, server, name in lan)
            continue
        bridge = PerSessionBridge(server) if name in PER_SESSION else SharedBridge(name, server)
        if isinstance(bridge, SharedBridge):
            shared.append(bridge)
        managers[name] = StreamableHTTPSessionManager(
            app=bridge, session_idle_timeout=PER_SESSION_IDLE_S if name in PER_SESSION else SESSION_IDLE_S,
            security_settings=no_sdk_host_check)
        # the session cap reads this private SDK map (mcp 1.27); refuse to run uncapped if it is renamed
        if not isinstance(getattr(managers[name], "_server_instances", None), dict):
            sys.exit("opencode-hub: mcp SDK changed (no _server_instances); session caps would not work")
    decide = httpx.AsyncClient(timeout=DECIDE_TIMEOUT_S)

    async def well_known(_request):
        text = await anyio.Path(PUBLIC, "wellknown.json").read_text()
        return Response(text.replace("{HUB}", HUB_URL), media_type="application/json",
                        headers={"cache-control": "no-store"})

    async def decide_hook(request):
        event = request.path_params["event"]
        if not DECIDE_EVENT_RE.match(event):
            return JSONResponse({}, status_code=400)
        body = b""
        async for chunk in request.stream():
            body += chunk
            if len(body) > DECIDE_MAX_BODY:
                return JSONResponse({}, status_code=413)
        try:
            with anyio.fail_after(DECIDE_TIMEOUT_S):
                agent = "opencode" if in_nets(request.scope, LOCAL) else "opencode-mac"
                res = await decide.post(f"{DECIDE_BASE}/hook/{agent}/{event}", content=body,
                                        headers={"content-type": "application/json"})
            return Response(res.content, status_code=res.status_code, media_type="application/json")
        except (httpx.HTTPError, TimeoutError):
            return JSONResponse({}, status_code=502)

    async def health(request):
        try:
            decide_ok = (await decide.get(f"{DECIDE_BASE}/health")).status_code == 200
        except httpx.HTTPError:
            decide_ok = False
        local = in_nets(request.scope, LOCAL)
        visible = lambda n: (n not in WORK_COPIES) if local else (n in lan)  # noqa: E731
        body = {"ok": True, "mcp": sorted(n for n in [*managers, *native] if visible(n)),
                "decide": decide_ok,
                "shared_running": sorted(b.name for b in shared if b.ready.is_set() and visible(b.name))}
        if TOKEN_FILE:  # F3: only with a token configured; unset keeps the pre-F3 body byte for byte
            body["auth"] = auth_mode()
        return JSONResponse(body)

    @contextlib.asynccontextmanager
    async def lifespan(_app):
        async with contextlib.AsyncExitStack() as stack:
            tg = await stack.enter_async_context(anyio.create_task_group())
            stack.callback(tg.cancel_scope.cancel)  # runs first on shutdown: stop children and reapers
            for bridge in shared:
                bridge.tg = tg
                if not bridge.started:
                    # prewarm: shared children come up with the hub, before any client connects, so
                    # /health reports them running immediately; supervise() retries a broken child
                    # forever without taking the hub down, and start_soon never blocks startup.
                    # started=True keeps run()'s lazy start from spawning a second supervisor.
                    bridge.started = True
                    tg.start_soon(bridge.supervise)
            for endpoint in native.values():
                tg.start_soon(endpoint.supervise)
                tg.start_soon(endpoint.reap)
            for manager in managers.values():
                await stack.enter_async_context(manager.run())
            stack.push_async_callback(decide.aclose)
            yield

    routes = [Route("/.well-known/opencode", well_known), Route("/health", health),
              Route("/decide/hook/opencode/{event}", decide_hook, methods=["POST"])]
    routes += [Route(f"/mcp/{name}", McpEndpoint(name, m, name in lan, name in WORK_COPIES),
                     methods=["GET", "POST", "DELETE"])
               for name, m in managers.items()]
    routes += [Route(f"/mcp/{name}", e, methods=["GET", "POST", "DELETE"]) for name, e in native.items()]
    routes += [Mount("/plugins", StaticFiles(directory=os.path.join(PUBLIC, "plugins")))]
    return Starlette(routes=routes, lifespan=lifespan)


def auth_mode() -> str:
    """For /health and the start log: off (no token configured), token, or token-file-unusable."""
    if not TOKEN_FILE:
        return "off"
    mode = "token" if EXPECTED_BEARER is not None else "token-file-unusable"
    return mode if TOKEN_ENFORCE else mode + "-report"


if __name__ == "__main__":
    if TOKEN_FILE:  # unset: no new log line (the pre-F3 start)
        log(f"auth: {auth_mode()} (off-box callers {'need it too' if TOKEN_OFFBOX else 'exempt'})")
    uvicorn.run(Guard(build_app()), host=BIND, port=PORT, log_level="warning", server_header=False,
                proxy_headers=False, timeout_graceful_shutdown=5)
